import * as vscode from 'vscode';
import { ConnectionManager } from './connectionManager';
import { t } from './i18n';

export async function exportConnections(connectionManager: ConnectionManager): Promise<void> {
  const conns = connectionManager.connections;
  if (conns.length === 0) {
    vscode.window.showInformationMessage(t('msg_noConnectionsToExport'));
    return;
  }
  const uri = await vscode.window.showSaveDialog({
    title: t('cmd.exportConnections'),
    defaultUri: vscode.Uri.file(`s3-connections-${new Date().toISOString().slice(0, 10)}.json`),
    filters: { JSON: ['json'] },
  });
  if (!uri) return;
  const payload = {
    type: 'vscode-s3-connections',
    version: 1,
    exportedAt: new Date().toISOString(),
    // strip internal id; it is regenerated on import
    connections: conns.map(({ id: _id, ...rest }) => rest),
  };
  try {
    await vscode.workspace.fs.writeFile(uri, Buffer.from(JSON.stringify(payload, null, 2), 'utf-8'));
    vscode.window.showInformationMessage(t('msg_exportSuccess', String(conns.length)));
  } catch (err: any) {
    vscode.window.showErrorMessage(t('msg_exportFailed', err?.message || String(err)));
  }
}

export async function importConnections(connectionManager: ConnectionManager): Promise<void> {
  const uris = await vscode.window.showOpenDialog({
    title: t('cmd.importConnections'),
    canSelectMany: false,
    filters: { JSON: ['json'] },
  });
  if (!uris || uris.length === 0) return;
  let data: unknown;
  try {
    data = JSON.parse(Buffer.from(await vscode.workspace.fs.readFile(uris[0])).toString('utf-8'));
  } catch {
    vscode.window.showErrorMessage(t('msg_importInvalidFile'));
    return;
  }
  let list: unknown[] | null = null;
  if (Array.isArray(data)) {
    list = data;
  } else if (data && typeof data === 'object' && Array.isArray((data as { connections?: unknown }).connections)) {
    list = (data as { connections: unknown[] }).connections;
  }
  if (!list) {
    vscode.window.showErrorMessage(t('msg_importInvalidFile'));
    return;
  }
  let imported = 0;
  let skipped = 0;
  const seenNames = new Set<string>();
  for (const raw of list) {
    const item = (raw ?? {}) as Record<string, unknown>;
    const name = typeof item.name === 'string' ? item.name.trim() : '';
    if (
      !name ||
      typeof item.endpoint !== 'string' || !item.endpoint ||
      typeof item.bucket !== 'string' || !item.bucket
    ) {
      skipped++;
      continue;
    }
    // Dedupe by name: skip names already stored or already seen in this file
    if (connectionManager.isNameTaken(name) || seenNames.has(name)) {
      skipped++;
      continue;
    }
    seenNames.add(name);
    try {
      await connectionManager.addConnection({
        id: '', // regenerated by addConnection
        name,
        endpoint: item.endpoint,
        region: typeof item.region === 'string' ? item.region : '',
        bucket: item.bucket,
        forcePathStyle: item.forcePathStyle === true,
        accessKeyId: typeof item.accessKeyId === 'string' ? item.accessKeyId : '',
        secretAccessKey: typeof item.secretAccessKey === 'string' ? item.secretAccessKey : '',
        isHuaweiOBS: item.isHuaweiOBS === true,
        proxyEnabled: item.proxyEnabled === true,
        proxyUrl: typeof item.proxyUrl === 'string' ? item.proxyUrl : undefined,
        proxyUsername: typeof item.proxyUsername === 'string' ? item.proxyUsername : undefined,
        proxyPassword: typeof item.proxyPassword === 'string' ? item.proxyPassword : undefined,
        noProxy: typeof item.noProxy === 'string' ? item.noProxy : undefined,
      });
      imported++;
    } catch {
      skipped++;
    }
  }
  vscode.window.showInformationMessage(t('msg_importSuccess', String(imported), String(skipped)));
}
